#define ARM64_REG_SIZE (8)

#define ARM64_THREAD_NUM_CALLER_REGS (18)
#define ARM64_THREAD_NUM_CALLEE_REGS (13)

#define ARM64_THREAD_CALLER_PUSH_SIZE (8*((ARM64_THREAD_NUM_CALLER_REGS+1)&~1))
#define ARM64_THREAD_CALLEE_PUSH_SIZE (8*((ARM64_THREAD_NUM_CALLEE_REGS+1)&~1))

#define ARM64_PUSHED_CALLER_REG_INDEX_X0  (0)
#define ARM64_PUSHED_CALLER_REG_INDEX_X1  (1)
#define ARM64_PUSHED_CALLER_REG_INDEX_X2  (2)
#define ARM64_PUSHED_CALLER_REG_INDEX_X3  (3)
#define ARM64_PUSHED_CALLER_REG_INDEX_X4  (4)
#define ARM64_PUSHED_CALLER_REG_INDEX_X5  (5)
#define ARM64_PUSHED_CALLER_REG_INDEX_X6  (6)
#define ARM64_PUSHED_CALLER_REG_INDEX_X7  (7)
#define ARM64_PUSHED_CALLER_REG_INDEX_X8  (8)
#define ARM64_PUSHED_CALLER_REG_INDEX_X9  (9)
#define ARM64_PUSHED_CALLER_REG_INDEX_X10 (10)
#define ARM64_PUSHED_CALLER_REG_INDEX_X11 (11)
#define ARM64_PUSHED_CALLER_REG_INDEX_X12 (12)
#define ARM64_PUSHED_CALLER_REG_INDEX_X13 (13)
#define ARM64_PUSHED_CALLER_REG_INDEX_X14 (14)
#define ARM64_PUSHED_CALLER_REG_INDEX_X15 (15)
