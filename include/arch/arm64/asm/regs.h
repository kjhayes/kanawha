#define ARM64_PUSHED_CALLEE_REG_INDEX_X29 (11)
#define ARM64_PUSHED_CALLEE_REG_INDEX_X30 (12)

#ifdef __ASSEMBLER__

#define SAVE_CALLER_REGS(GPR_PTR)\
stp x0, x1,   [GPR_PTR, 0x00]; \
stp x2, x3,   [GPR_PTR, 0x10]; \
stp x4, x5,   [GPR_PTR, 0x20]; \
stp x6, x7,   [GPR_PTR, 0x30]; \
stp x8, x9,   [GPR_PTR, 0x40]; \
stp x10, x11, [GPR_PTR, 0x50]; \
stp x12, x13, [GPR_PTR, 0x60]; \
stp x14, x15, [GPR_PTR, 0x70]; \
stp x16, x17, [GPR_PTR, 0x80]; \

#define SAVE_CALLEE_REGS(GPR_PTR)\
stp x18, x19, [GPR_PTR, 0x00]; \
stp x20, x21, [GPR_PTR, 0x10]; \
stp x22, x23, [GPR_PTR, 0x20]; \
stp x24, x25, [GPR_PTR, 0x30]; \
stp x26, x27, [GPR_PTR, 0x40]; \
stp x28, x29, [GPR_PTR, 0x50]; \
stp x30, xzr, [GPR_PTR, 0x60];

#define RESTORE_CALLER_REGS(GPR_PTR)\
ldp x0, x1,   [GPR_PTR, 0x00]; \
ldp x2, x3,   [GPR_PTR, 0x10]; \
ldp x4, x5,   [GPR_PTR, 0x20]; \
ldp x6, x7,   [GPR_PTR, 0x30]; \
ldp x8, x9,   [GPR_PTR, 0x40]; \
ldp x10, x11, [GPR_PTR, 0x50]; \
ldp x12, x13, [GPR_PTR, 0x60]; \
ldp x14, x15, [GPR_PTR, 0x70]; \
ldp x16, x17, [GPR_PTR, 0x80]; \

#define RESTORE_CALLEE_REGS(GPR_PTR)\
ldp x18, x19, [GPR_PTR, 0x00]; \
ldp x20, x21, [GPR_PTR, 0x10]; \
ldp x22, x23, [GPR_PTR, 0x20]; \
ldp x24, x25, [GPR_PTR, 0x30]; \
ldp x26, x27, [GPR_PTR, 0x40]; \
ldp x28, x29, [GPR_PTR, 0x50]; \
ldp x30, xzr, [GPR_PTR, 0x60];

#define PUSH_CALLER_REGS()\
sub sp, sp, ARM64_THREAD_CALLER_PUSH_SIZE;\
SAVE_CALLER_REGS(sp);

#define POP_CALLER_REGS()\
RESTORE_CALLER_REGS(sp);\
add sp, sp, ARM64_THREAD_CALLER_PUSH_SIZE;

#define PUSH_CALLEE_REGS()\
sub sp, sp, ARM64_THREAD_CALLEE_PUSH_SIZE;\
SAVE_CALLEE_REGS(sp);

#define POP_CALLEE_REGS()\
RESTORE_CALLEE_REGS(sp);\
add sp, sp, ARM64_THREAD_CALLEE_PUSH_SIZE;

#else

_Static_assert(ARM64_THREAD_CALLER_PUSH_SIZE % 16 == 0, "ARM64 Thread Caller Register Frame Must Be A Multiple of 16-bytes!");
_Static_assert(ARM64_THREAD_CALLER_PUSH_SIZE % 16 == 0, "ARM64 Thread Caller Register Frame Must Be A Multiple of 16-bytes!");

#endif
#endif
