#ifndef __KANAWHA__ARM64_MMU_H__
#define __KANAWHA__ARM64_MMU_H__

#define ARM64_PAGETABLE_ENTRY_SIZE (8)
#define ARM64_PAGETABLE_ENTRY_SIZE_ORDER (3)

#define ARM64_PAGE_4KB (0x1000)
#define ARM64_PAGE_16KB (0x4000)
#define ARM64_PAGE_64KB (0x10000)

// 48-bit Virtual Addresses, 4KB Granule
#define ARM64_V48G4_GRANULE (ARM64_PAGE_4KB)
#define ARM64_V48G4_GRANULE_ORDER (12)

#define ARM64_V48G4_L3_ENTRIES_ORDER (9)
#define ARM64_V48G4_L2_ENTRIES_ORDER (9)
#define ARM64_V48G4_L1_ENTRIES_ORDER (9)
#define ARM64_V48G4_L0_ENTRIES_ORDER (9)

#define ARM64_V48G4_L3_ENTRIES (512)
#define ARM64_V48G4_L2_ENTRIES (512)
#define ARM64_V48G4_L1_ENTRIES (512)
#define ARM64_V48G4_L0_ENTRIES (512)

#define ARM64_V48G4_L3_INDEX_SHIFT (12)
#define ARM64_V48G4_L3_INDEX_MASK  (0x1FF)
#define ARM64_V48G4_L2_INDEX_SHIFT (21)
#define ARM64_V48G4_L2_INDEX_MASK  (0x1FF)
#define ARM64_V48G4_L1_INDEX_SHIFT (30)
#define ARM64_V48G4_L1_INDEX_MASK  (0x1FF)
#define ARM64_V48G4_L0_INDEX_SHIFT (39)
#define ARM64_V48G4_L0_INDEX_MASK  (0x1FF)

#define ARM64_V48G4_L3_ENTRY_REGION (ARM64_V48G4_GRANULE)
#define ARM64_V48G4_L2_ENTRY_REGION (ARM64_V48G4_L3_ENTRY_REGION*ARM64_V48G4_L3_ENTRIES)
#define ARM64_V48G4_L1_ENTRY_REGION (ARM64_V48G4_L2_ENTRY_REGION*ARM64_V48G4_L2_ENTRIES)
#define ARM64_V48G4_L0_ENTRY_REGION (ARM64_V48G4_L1_ENTRY_REGION*ARM64_V48G4_L1_ENTRIES)

#define ARM64_V48G4_L3_TABLE_SIZE (ARM64_V48G4_L3_ENTRIES*ARM64_PAGETABLE_ENTRY_SIZE)
#define ARM64_V48G4_L2_TABLE_SIZE (ARM64_V48G4_L2_ENTRIES*ARM64_PAGETABLE_ENTRY_SIZE)
#define ARM64_V48G4_L1_TABLE_SIZE (ARM64_V48G4_L1_ENTRIES*ARM64_PAGETABLE_ENTRY_SIZE)
#define ARM64_V48G4_L0_TABLE_SIZE (ARM64_V48G4_L0_ENTRIES*ARM64_PAGETABLE_ENTRY_SIZE)

#define ARM64_V48G4_L3_TABLE_SIZE_ORDER (ARM64_V48G4_L3_ENTRIES_ORDER+ARM64_PAGETABLE_ENTRY_SIZE_ORDER)
#define ARM64_V48G4_L2_TABLE_SIZE_ORDER (ARM64_V48G4_L2_ENTRIES_ORDER+ARM64_PAGETABLE_ENTRY_SIZE_ORDER)
#define ARM64_V48G4_L1_TABLE_SIZE_ORDER (ARM64_V48G4_L1_ENTRIES_ORDER+ARM64_PAGETABLE_ENTRY_SIZE_ORDER)
#define ARM64_V48G4_L0_TABLE_SIZE_ORDER (ARM64_V48G4_L0_ENTRIES_ORDER+ARM64_PAGETABLE_ENTRY_SIZE_ORDER)

// MAIR (this is overly simplistic but should work)
#define ARM64_MAIR_DEFAULT_VALUE ((0xFFul << 0) | (0x00ul << 8))
#define ARM64_MAIR_INDEX_NORMAL_CACHEABLE   (0x0)
#define ARM64_MAIR_INDEX_DEVICE_UNCACHEABLE (0x1)

#ifndef __ASSEMBLER__
_Static_assert(ARM64_V48G4_L3_TABLE_SIZE == 0x1000, "ARM64_V48G4_L3_TABLE_SIZE is not 4KiB");
_Static_assert(ARM64_V48G4_L2_TABLE_SIZE == 0x1000, "ARM64_V48G4_L2_TABLE_SIZE is not 4KiB");
_Static_assert(ARM64_V48G4_L1_TABLE_SIZE == 0x1000, "ARM64_V48G4_L1_TABLE_SIZE is not 4KiB");
_Static_assert(ARM64_V48G4_L0_TABLE_SIZE == 0x1000, "ARM64_V48G4_L0_TABLE_SIZE is not 4KiB");
#endif

#endif
